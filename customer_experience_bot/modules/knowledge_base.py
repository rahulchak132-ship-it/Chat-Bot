class KnowledgeBase:
    """Enterprise Knowledge Base with document ingestion and keyword/TF-IDF retrieval."""

    def __init__(self, upload_dir: str = "uploads"):
        self.upload_dir = upload_dir
        self.documents: List[Dict[str, Any]] = []
        self.chunks: List[Dict[str, Any]] = []
        self._load_default_kb()

    def _load_default_kb(self):
        """Loads default verified company policies and guidelines."""
        for doc in DEFAULT_KNOWLEDGE_DOCUMENTS:
            self.add_document(doc["doc_id"], doc["title"], doc["content"], doc["category"])

    def add_document(self, doc_id: str, title: str, text: str, category: str = "General"):
        """Adds a document to the knowledge base and splits it into searchable passages."""
        clean_text = text.strip()
        if not clean_text:
            return

        doc_entry = {
            "doc_id": doc_id,
            "title": title,
            "category": category,
            "content": clean_text
        }
        self.documents.append(doc_entry)

        # Split into semantic paragraphs / chunks (150-300 words)
        paragraphs = [p.strip() for p in clean_text.split("\n\n") if p.strip()]
        for idx, para in enumerate(paragraphs):
            # Clean tokens
            tokens = set(re.findall(r"\w+", para.lower()))
            self.chunks.append({
                "doc_id": doc_id,
                "title": title,
                "chunk_id": f"{doc_id}_c{idx}",
                "category": category,
                "text": para,
                "tokens": tokens
            })

    def search(self, query: str, top_k: int = 3) -> List[Dict[str, Any]]:
        """
        Retrieves top-k relevant knowledge base passages using token overlap
        and domain term weighting. Modular for future vector embedding replacement.
        """
        query_tokens = set(re.findall(r"\w+", query.lower()))
        # Remove common stop words
        stop_words = {"the", "a", "an", "is", "are", "in", "at", "to", "for", "of", "and", "or", "my", "your", "i", "we", "it", "this", "that"}
        filtered_query = query_tokens - stop_words
        if not filtered_query:
            filtered_query = query_tokens

        scored_chunks = []
        for chunk in self.chunks:
            chunk_tokens = chunk["tokens"]
            overlap = len(filtered_query.intersection(chunk_tokens))
            if overlap > 0:
                # Add extra weight if title matches
                title_tokens = set(re.findall(r"\w+", chunk["title"].lower()))
                title_overlap = len(filtered_query.intersection(title_tokens))
                score = overlap + (title_overlap * 2.0)
                scored_chunks.append((score, chunk))

        scored_chunks.sort(key=lambda x: x[0], reverse=True)
        return [chunk for score, chunk in scored_chunks[:top_k]]

    def parse_uploaded_file(self, file_path: str, filename: str) -> Optional[str]:
        """
        Parses uploaded documents (PDF, DOCX, TXT, CSV, XLSX)
        and indexes them into the knowledge base.
        """
        ext = os.path.splitext(filename)[1].lower()
        extracted_text = ""

        try:
            if ext == ".txt":
                with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                    extracted_text = f.read()

            elif ext == ".pdf":
                try:
                    import pypdf
                    reader = pypdf.PdfReader(file_path)
                    pages = [page.extract_text() or "" for page in reader.pages]
                    extracted_text = "\n\n".join(pages)
                except ImportError:
                    extracted_text = f"[PDF Parser fallback: pypdf not available for {filename}]"

            elif ext in [".docx", ".doc"]:
                try:
                    import docx
                    doc = docx.Document(file_path)
                    extracted_text = "\n\n".join([p.text for p in doc.paragraphs if p.text])
                except ImportError:
                    extracted_text = f"[DOCX Parser fallback: python-docx not available for {filename}]"

            elif ext == ".csv":
                with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                    reader = csv.reader(f)
                    rows = [" | ".join(row) for row in reader]
                    extracted_text = "\n".join(rows)

            elif ext in [".xlsx", ".xls"]:
                try:
                    import pandas as pd
                    excel_data = pd.read_excel(file_path, sheet_name=None)
                    sheets_text = []
                    for sheet_name, df in excel_data.items():
                        sheets_text.append(f"Sheet: {sheet_name}\n" + df.to_string(index=False))
                    extracted_text = "\n\n".join(sheets_text)
                except ImportError:
                    extracted_text = f"[Excel Parser fallback: pandas/openpyxl not available for {filename}]"

            if extracted_text.strip():
                doc_id = f"UPL-{len(self.documents)+1:03d}"
                self.add_document(doc_id, filename, extracted_text, category="Uploaded Company Document")
                return doc_id
        except Exception as e:
            print(f"Error parsing uploaded document {filename}: {e}")
            return None

        return None

# Global Singleton Instance
_kb_instance: Optional[KnowledgeBase] = None

def get_knowledge_base() -> KnowledgeBase:
    global _kb_instance
    if _kb_instance is None:
        _kb_instance = KnowledgeBase()
    return _kb_instance
